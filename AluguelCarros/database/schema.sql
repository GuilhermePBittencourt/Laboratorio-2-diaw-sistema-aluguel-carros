-- Esquema do banco do Sistema de Aluguel de Carros (PostgreSQL / Supabase)
--
-- Como usar no Supabase: abra "SQL Editor", cole este arquivo e execute.
-- Os nomes de tabelas e colunas seguem o mapeamento JPA do back-end (snake_case),
-- então a aplicação funciona com DDL_AUTO=validate ou DDL_AUTO=update.
--
-- Segurança: o Supabase expõe as tabelas do schema "public" pela API REST (PostgREST).
-- Como o acesso aos dados é feito somente pelo back-end Spring Boot (conexão JDBC), ligamos o
-- Row Level Security em todas as tabelas, sem políticas: a chave pública (anon) não lê nada.

create table if not exists usuario (
    id          bigint generated by default as identity primary key,
    login       varchar(50)  not null unique,
    senha_hash  varchar(255) not null,
    perfil      varchar(20)  not null check (perfil in ('CLIENTE', 'AGENTE'))
);

create table if not exists cliente (
    id          bigint generated by default as identity primary key,
    rg          varchar(20)  not null,
    cpf         varchar(11)  not null unique,
    nome        varchar(120) not null,
    endereco    varchar(255) not null,
    profissao   varchar(80)  not null,
    usuario_id  bigint       not null unique references usuario (id)
);

-- Rendimentos do cliente (entidade empregadora e valor). A regra "no máximo 3" é validada pela aplicação;
-- o trigger abaixo garante a mesma regra mesmo para quem acessar o banco diretamente.
create table if not exists cliente_rendimento (
    cliente_id            bigint        not null references cliente (id) on delete cascade,
    entidade_empregadora  varchar(120)  not null,
    valor                 numeric(12,2) not null check (valor >= 0)
);

create index if not exists idx_cliente_rendimento_cliente on cliente_rendimento (cliente_id);

create or replace function limitar_rendimentos() returns trigger as $$
begin
    if (select count(*) from cliente_rendimento where cliente_id = new.cliente_id) >= 3 then
        raise exception 'Um cliente pode ter no máximo 3 rendimentos';
    end if;
    return new;
end;
$$ language plpgsql;

drop trigger if exists trg_limitar_rendimentos on cliente_rendimento;
create trigger trg_limitar_rendimentos
    before insert on cliente_rendimento
    for each row execute function limitar_rendimentos();

create table if not exists agente (
    id          bigint generated by default as identity primary key,
    nome        varchar(120) not null,
    tipo        varchar(20)  not null check (tipo in ('EMPRESA', 'BANCO')),
    usuario_id  bigint       not null unique references usuario (id)
);

create table if not exists automovel (
    id            bigint generated by default as identity primary key,
    matricula     varchar(20) not null unique,
    ano           integer     not null,
    marca         varchar(60) not null,
    modelo        varchar(60) not null,
    placa         varchar(8)  not null unique,
    proprietario  varchar(20) not null check (proprietario in ('CLIENTE', 'EMPRESA', 'BANCO'))
);

create table if not exists pedido_aluguel (
    id               bigint generated by default as identity primary key,
    cliente_id       bigint       not null references cliente (id),
    automovel_id     bigint       not null references automovel (id),
    data_inicio      date         not null,
    data_fim         date         not null,
    status           varchar(20)  not null
                     check (status in ('EM_ANALISE', 'APROVADO', 'REPROVADO', 'CANCELADO', 'CONTRATADO')),
    parecer          varchar(500),
    avaliado_por_id  bigint       references agente (id),
    criado_em        timestamptz  not null,
    atualizado_em    timestamptz  not null,
    check (data_fim > data_inicio)
);

create index if not exists idx_pedido_cliente on pedido_aluguel (cliente_id);
create index if not exists idx_pedido_automovel_periodo on pedido_aluguel (automovel_id, data_inicio, data_fim);

create table if not exists contrato (
    id                bigint generated by default as identity primary key,
    pedido_id         bigint        not null unique references pedido_aluguel (id),
    proprietario      varchar(20)   not null check (proprietario in ('CLIENTE', 'EMPRESA', 'BANCO')),
    agente_id         bigint        not null references agente (id),
    banco_credito_id  bigint        references agente (id),
    valor_credito     numeric(12,2),
    data_contrato     timestamptz   not null,
    -- crédito: banco e valor andam juntos
    check ((banco_credito_id is null) = (valor_credito is null))
);

alter table usuario            enable row level security;
alter table cliente            enable row level security;
alter table cliente_rendimento enable row level security;
alter table agente             enable row level security;
alter table automovel          enable row level security;
alter table pedido_aluguel     enable row level security;
alter table contrato           enable row level security;
